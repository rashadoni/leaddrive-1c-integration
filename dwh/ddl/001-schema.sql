-- ------------------------------- FAKT-lar ----------------------------------
-- Qaytarmalar: doc_type = -1, məbləğ/miqdar MÜSBƏT saxlanılır →
-- net = SUM(x * doc_type). (plan: "Boşluq siyahısı" №2)

CREATE TABLE dwh.fact_sales_line (
  date_key        date   NOT NULL,
  org_key         bigint NOT NULL,
  warehouse_key   bigint NOT NULL,
  customer_key    bigint NOT NULL,
  product_key     bigint NOT NULL,
  series_key      bigint,                      -- seriya uçotu olmayan mallar üçün NULL
  doc_type        smallint NOT NULL,           -- 1 = satış, -1 = qaytarma
  doc_ref         char(32) NOT NULL,           -- 1C sənəd _IDRRef hex
  doc_no          text,
  line_no         int    NOT NULL,
  qty             numeric(18,3) NOT NULL,
  revenue_gross   numeric(18,4) NOT NULL,      -- ƏDV DAXİL (metrik memo §1)
  vat_amount      numeric(18,4) NOT NULL DEFAULT 0,
  cost_avg        numeric(18,4),               -- orta maya (statusla birgə oxunmalı)
  cost_status     smallint NOT NULL DEFAULT 0, -- 0 = ilkin, 1 = yekun (ay bağlanıb)
  return_of_doc_ref char(32),                  -- qaytarmanın bağlandığı satış (varsa)
  PRIMARY KEY (date_key, doc_ref, line_no)
) PARTITION BY RANGE (date_key);

-- Nümunə partisiyalar (ETL avtomatik yaradır — etl/src/lib/pg.ts ensureMonthPartition)
