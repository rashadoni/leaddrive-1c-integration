-- ------------------------- MART (semantik qat) ------------------------------
-- NL→SQL və Metabase YALNIZ mart.* görür. View-lar Gate 1-dən sonra real
-- sütunlarla yekunlaşır; aşağıdakı imzalar müqavilə xarakterlidir.

CREATE OR REPLACE VIEW mart.v_sales_daily AS
SELECT
  f.date_key                                       AS satis_tarixi,
  o.name                                           AS teskilat,
  c.name                                           AS musteri,
  p.name                                           AS mehsul,
  p.category                                       AS kateqoriya,
  SUM(f.qty * f.doc_type)                          AS miqdar_net,
  SUM(f.revenue_gross * f.doc_type)                AS dovriyye_edv_daxil,
  SUM(f.vat_amount * f.doc_type)                   AS edv,
  SUM((f.revenue_gross - COALESCE(f.cost_avg,0) * f.qty) * f.doc_type) AS marja_ilkin,
  MIN(f.cost_status)                               AS cost_status   -- 0 görünərsə "ilkin"
FROM dwh.fact_sales_line f
JOIN dwh.dim_org      o ON o.org_key      = f.org_key
JOIN dwh.dim_customer c ON c.customer_key = f.customer_key
JOIN dwh.dim_product  p ON p.product_key  = f.product_key
GROUP BY 1,2,3,4,5;

CREATE OR REPLACE VIEW mart.v_stock_expiry AS
SELECT
  s.date_key                                       AS tarix,
  w.name                                           AS anbar,
  p.name                                           AS mehsul,
  se.batch_no                                      AS partiya,
  se.expiry_date                                   AS son_istifade,
  (se.expiry_date - s.date_key)                    AS qalan_gun,
  CASE
    WHEN se.expiry_date IS NULL                    THEN 'seriyasiz'
    WHEN se.expiry_date - s.date_key < 90          THEN 'qirmizi (<3 ay)'
    WHEN se.expiry_date - s.date_key < 180         THEN 'sari (3-6 ay)'
    ELSE 'yasil (>6 ay)'
  END                                              AS expiry_zona,   -- M8 təklifi
  s.qty,
  s.value_avg
FROM dwh.fact_stock_eod s
JOIN dwh.dim_warehouse w  ON w.warehouse_key = s.warehouse_key
JOIN dwh.dim_product   p  ON p.product_key   = s.product_key
LEFT JOIN dwh.dim_series se ON se.series_key = s.series_key;
